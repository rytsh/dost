"""art/items/<item> -> assets/items.png and assets/items_atlas.rs.

Run from the repo root with the Sprite Forge venv (or `make atlas`, after pack_atlas.py).
Toys (bone, pumpkin) have one picture and a pin that goes into the mouth on idle's first frame.
Worn items (hats) have one picture per pose (art/fit_worn.py: drawn by the image model
on that pose), with where its top-left goes relative to the feet point. The renderer takes the
pose of each frame's action (happy has one per frame) and follows the head from that pose's
first frame (`HEAD` in dog_atlas.rs).
"""

import glob
import json

from PIL import Image

ANIMS = ["idle", "walk", "sit", "bark", "happy", "sleep", "held", "sad"]
POSES = ["idle", "walk", "sit", "bark", "happy0", "sleep", "held", "sad", "happy1", "happy2", "happy3"]
# name, pin in the item (x, y), target relative to the feet point on idle 0.
TOYS = {"bone": ((17, 10), (44, -66)), "pumpkin": ((14, 3), (44, -68))}
WORN = ["beanie", "party", "witch", "santa"]
ORDER = ["bone", "beanie", "party", "witch", "santa", "pumpkin"]

pictures = []  # (image, label)
for n in ORDER:
    if n in TOYS:
        pictures.append((Image.open(sorted(glob.glob(f"art/items/{n}/frames/*.png"))[0]).convert("RGBA"), n))
    else:
        for p in POSES:
            pictures.append((Image.open(f"art/items/{n}/{p}.png").convert("RGBA"), f"{n} {p}"))

# Shelf packing: rows of at most WIDTH pixels.
WIDTH = 1024
rects, x, y, row_h = [], 0, 0, 0
for im, _ in pictures:
    if x + im.width > WIDTH:
        x, y, row_h = 0, y + row_h + 1, 0
    rects.append((x, y, im.width, im.height))
    x += im.width + 1
    row_h = max(row_h, im.height)
atlas = Image.new("RGBA", (WIDTH, y + row_h))
for (im, _), (rx, ry, _, _) in zip(pictures, rects):
    atlas.paste(im, (rx, ry))
atlas.save("assets/items.png", optimize=True)

it = iter(zip(pictures, rects))
with open("assets/items_atlas.rs", "w") as f:
    f.write("// Generated by art/pack_items.py (make atlas). Do not edit.\n")
    f.write("/// One entry per item in `assets/items.png`, in `Item` order. Toys: one picture with a pin\n")
    f.write("/// that goes on idle's first frame. Worn items: one picture per pose (`POSES`), the pin at\n")
    f.write("/// its top-left and where that goes in the pose's first frame; all relative to the feet point.\n")
    f.write(f"pub const POSES: [&str; {len(POSES)}] = {json.dumps(POSES)};\n".replace("[\"", "[\"").replace("\", \"", "\", \""))
    f.write(f"pub const ITEMS: [ItemSprite; {len(ORDER)}] = [\n")
    for n in ORDER:
        if n in TOYS:
            (_, label), r = next(it)
            pin, at = TOYS[n]
            sprites = ", ".join([f"ItemPose {{ rect: {r}, pin: {pin}, at: {at} }}"] * len(POSES))
            f.write(f"    ItemSprite {{ worn: false, poses: [{sprites}] }}, // {n}\n")
        else:
            worn = json.load(open(f"art/items/{n}/worn.json"))
            parts = []
            for p in POSES:
                (_, label), r = next(it)
                at = tuple(worn[p])
                parts.append(f"ItemPose {{ rect: {r}, pin: (0, 0), at: {at} }}")
            f.write(f"    ItemSprite {{ worn: true, poses: [\n        " + ",\n        ".join(parts) + f",\n    ] }}, // {n}\n")
    f.write("];\n")
print("items:", ORDER, "atlas", atlas.size)
