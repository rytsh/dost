"""art/items/<item>/frames -> assets/items.png and assets/items_atlas.rs.

Run from the repo root with the Sprite Forge venv (or `make atlas`, after pack_atlas.py).
Items are packed in one row; each gets a pin (where it attaches, item pixels) and the point on
idle's first frame it attaches to, relative to the feet point. Hats and glasses follow the
head (`HEAD` in dog_atlas.rs), the bandana follows the collar (`NECK`), the bone sits in the mouth.
"""

import glob

from PIL import Image

# name, pin in the item (x, y), target relative to the feet point on idle 0, follows.
ITEMS = [
    ("bone", (17, 10), (44, -66), "head"),
    ("beanie", (24, 38), (30, -108), "head"),
    ("party", (17, 40), (30, -110), "head"),
    ("witch", (30, 40), (28, -106), "head"),
    ("santa", (30, 36), (28, -106), "head"),
    ("bandana", (22, 6), (0, 0), "neck"),
    ("glasses", (24, 9), (28, -87), "head"),
    ("pumpkin", (14, 3), (44, -68), "head"),
]

ims = [Image.open(sorted(glob.glob(f"art/items/{n}/frames/*.png"))[0]).convert("RGBA") for n, *_ in ITEMS]
w = sum(i.width + 1 for i in ims)
h = max(i.height for i in ims)
atlas = Image.new("RGBA", (w, h))
rects = []
x = 0
for im in ims:
    atlas.paste(im, (x, 0))
    rects.append((x, 0, im.width, im.height))
    x += im.width + 1
atlas.save("assets/items.png", optimize=True)

with open("assets/items_atlas.rs", "w") as f:
    f.write("// Generated by art/pack_items.py (make atlas). Do not edit.\n")
    f.write("/// One entry per item in `assets/items.png`, in `Item` order: (x, y, w, h) in the atlas,\n")
    f.write("/// the pin inside it, where the pin goes on idle's first frame (relative to the feet point)\n")
    f.write("/// and whether it follows the collar (`true`) or the head.\n")
    f.write(f"pub const ITEMS: [ItemSprite; {len(ITEMS)}] = [\n")
    for (name, pin, at, kind), r in zip(ITEMS, rects):
        f.write(
            f"    ItemSprite {{ rect: {r}, pin: {pin}, at: {at}, neck: {str(kind == 'neck').lower()} }}, // {name}\n"
        )
    f.write("];\n")
print("items:", [n for n, *_ in ITEMS], "atlas", atlas.size)
